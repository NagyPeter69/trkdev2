#!/usr/bin/env bash
# Regenerates engine/build_info.php from the current git state and VERSION
# file. Run this after committing (build metadata reflects the commit HEAD
# was on when this ran, not the commit it ends up bundled into - that's
# normal for build-info files). The deploy script runs this automatically
# before shipping to a target.
set -euo pipefail
cd "$(dirname "$0")/.."

VERSION=$(cat VERSION 2>/dev/null || echo "0.0.0")
BUILD_HASH=$(git rev-parse --short HEAD 2>/dev/null || echo "unknown")
BUILD_DATE=$(git log -1 --format=%ci 2>/dev/null || date '+%Y-%m-%d %H:%M:%S %z')

cat > engine/build_info.php << EOF
<?php
// Auto-generated by bin/update-build-info.sh - do not edit by hand.
define( 'APP_VERSION', '${VERSION}' );
define( 'APP_BUILD', '${BUILD_HASH}' );
define( 'APP_BUILD_DATE', '${BUILD_DATE}' );
?>
EOF

echo "engine/build_info.php updated: v${VERSION} (${BUILD_HASH}, ${BUILD_DATE})"
